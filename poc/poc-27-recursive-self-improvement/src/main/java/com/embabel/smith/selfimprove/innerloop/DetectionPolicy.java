package com.embabel.smith.selfimprove.innerloop;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import com.embabel.agent.skills.script.ScriptLanguage;
import com.embabel.agent.skills.script.SkillScript;

/**
 * A detection policy: a name and the JavaScript source that decides which recorded
 * failures count as defects. This is the artifact design D1 puts on the mutable side —
 * generated, versioned as a new variant, and interpreted by an interpreter a generation
 * cannot edit.
 *
 * <p>
 * A policy is written out as a real skill folder so it runs through POC 26's engine by
 * the same door a generated skill script uses: {@link #toSkillScript(Path)} produces the
 * {@link SkillScript} handle the engine takes. Nothing here runs it, and nothing here
 * runs it in the referee (design D9).
 *
 * @param name the variant name, also the skill folder name the script is written into
 * @param source the JavaScript source
 * @author Ivan Rodriguez
 */
public record DetectionPolicy(String name, String source) {

	/**
	 * The file name every policy is written under, inside the skill's {@code scripts/}
	 * folder.
	 */
	public static final String SCRIPT_FILE = "policy.js";

	/**
	 * The human-written policy: the baseline the generated variants are compared to.
	 * @return the policy read from {@code policies/handwritten-detect.js}.
	 */
	public static DetectionPolicy handWritten() {
		return new DetectionPolicy("handwritten-detect", readResource("/policies/handwritten-detect.js"));
	}

	/**
	 * Write this policy as a skill folder and hand back the script handle the engine
	 * takes.
	 * @param workDir directory to create the skill folder under; each run gets its own
	 * @return the script to hand {@code SkillScriptExecutionEngine.execute}.
	 */
	public SkillScript toSkillScript(Path workDir) {
		if (!this.name.matches("[a-z0-9][a-z0-9-]{1,63}")) {
			throw new IllegalArgumentException(
					"policy name '" + this.name + "' is not a lowercase slug, so it cannot be a skill folder name");
		}
		Path skillDir = workDir.resolve(this.name);
		try {
			Files.createDirectories(skillDir.resolve("scripts"));
			Files.writeString(skillDir.resolve("SKILL.md"),
					"---\nname: " + this.name
							+ "\ndescription: POC 27 detection policy, run only inside POC 26's script engine.\n---\n\n"
							+ "Generated by the inner loop. See src/main/resources/policies/README.md.\n",
					StandardCharsets.UTF_8);
			Files.writeString(skillDir.resolve("scripts").resolve(SCRIPT_FILE), this.source, StandardCharsets.UTF_8);
		}
		catch (IOException ex) {
			throw new UncheckedIOException(
					"could not write the policy script for '" + this.name + "': " + ex.getMessage(), ex);
		}
		return new SkillScript(this.name, SCRIPT_FILE, ScriptLanguage.JAVASCRIPT, skillDir);
	}

	private static String readResource(String resource) {
		try (InputStream in = DetectionPolicy.class.getResourceAsStream(resource)) {
			if (in == null) {
				throw new IllegalStateException("policy resource '" + resource + "' is not on the classpath");
			}
			return new String(in.readAllBytes(), StandardCharsets.UTF_8);
		}
		catch (IOException ex) {
			throw new UncheckedIOException("could not read the policy resource '" + resource + "'", ex);
		}
	}

}
