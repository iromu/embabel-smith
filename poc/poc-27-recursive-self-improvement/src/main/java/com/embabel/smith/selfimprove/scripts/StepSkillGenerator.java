package com.embabel.smith.selfimprove.scripts;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

import com.embabel.agent.skills.script.ScriptLanguage;
import com.embabel.agent.skills.script.SkillScript;
import com.embabel.smith.builder.core.PackName;
import com.embabel.smith.builder.core.PromptData;
import com.embabel.smith.builder.core.SpecPromptCaller;
import com.embabel.smith.builder.skill.LlmJson;
import com.embabel.smith.builder.skill.Skill;
import com.embabel.smith.builder.skill.SkillGenerator;
import com.embabel.smith.builder.skill.SkillMdValidator;
import com.embabel.smith.builder.skill.SkillPrompts;
import com.embabel.smith.common.model.ActionStepSpec;
import com.embabel.smith.common.model.AgentSpec;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

/**
 * Turns one action step of a generated process into a skill folder that carries an
 * executable script: the product's own {@link SkillGenerator} writes the {@code SKILL.md}
 * frontmatter and body, and a second call writes the JavaScript that goes under
 * {@code scripts/}.
 *
 * <p>
 * <b>The skill is generated by product code, not paraphrased by this one.</b> The
 * generator is constructed with {@link SkillPrompts#generateSkill()} — the prompt
 * {@code SkillBuilderService} runs — so the frontmatter this class produces is the
 * artifact the product's {@link SkillMdValidator} gate was written to judge. The script
 * is the part the product does not have: {@code docs/08-builder.md} records the skill
 * target as {@code SKILL.md} plus {@code evals.json} and nothing else, so a
 * {@code scripts/} folder is this POC's addition, and {@code skill-scripts} is the
 * surface {@code evidence/MUTABILITY.md} puts on the mutable side.
 *
 * <p>
 * Both model calls sit behind the builder's {@link SpecPromptCaller} seam, so the whole
 * generation is offline-testable with canned answers, and the production caller is
 * {@code AiSpecPromptCaller} — the same Embabel {@code Ai} layer the process generation
 * uses.
 *
 * <p>
 * The script prompt is a constant rather than a bundled resource because a POC resource
 * is frozen evidence and this prompt is a mutable surface: what follows is exactly what a
 * generated script is allowed to reach, so it names POC 26's globals and refuses the four
 * things its hardening denies.
 *
 * @author Ivan Rodriguez
 */
public final class StepSkillGenerator {

	private static final ObjectMapper JSON = new ObjectMapper();

	/**
	 * The system prompt for the script call. It states POC 26's guest surface verbatim —
	 * {@code args}, {@code stdin}, {@code console}, {@code process.argv},
	 * {@code process.exit}, {@code readFile}, {@code writeFile} — and nothing else,
	 * because a script that assumes a Node global it was never given fails at run time
	 * rather than at generation time.
	 */
	public static final String SCRIPT_PROMPT = """
			You write one JavaScript file for the scripts/ folder of an Agent Skill.

			The file runs inside a hardened in-JVM JavaScript interpreter, not inside Node. The only
			globals it is given are:
			  args                 an array of the string arguments the caller passed
			  stdin                the text piped in, as a string
			  console.log/info/debug   writes to captured stdout
			  console.warn/error       writes to captured stderr
			  process.argv         the same args array
			  process.exit(code)   stop the script with that exit code
			  process.env          always empty
			  readFile(name)       read a file that was staged for this run, by basename
			  writeFile(name, text)  write a file into this run's output directory

			There is no require, no module, no __dirname, no filesystem, no network, no child
			process, no thread, and no way to name a host class. Do not use any of them.

			The script must do its work from stdin and args alone, print what it produced to
			stdout, and exit 0 on success or a non-zero code when it could not do the work.

			Answer with a single JSON object and nothing else:
			{"script": "<the JavaScript source>"}
			""";

	private final SpecPromptCaller caller;

	private final SkillGenerator generator;

	/**
	 * Create a generator over the builder's model seam.
	 * @param caller the model seam; {@code AiSpecPromptCaller} in a live run and a canned
	 * answer offline
	 */
	public StepSkillGenerator(SpecPromptCaller caller) {
		this.caller = caller;
		this.generator = new SkillGenerator(caller, SkillPrompts.generateSkill());
	}

	/**
	 * Generates the skill for one step and writes the folder.
	 * @param agent the agent that owns the step — its name namespaces the skill, because
	 * a pack folder is named after its pack and two agents can share a step name
	 * @param step the action step the skill is generated from
	 * @param skillsDir directory to create the skill folder under
	 * @return the generated skill, on disk.
	 * @throws IllegalStateException when either model call answers with nothing to write
	 */
	public Generated generate(AgentSpec agent, ActionStepSpec step, Path skillsDir) {
		String skillName = PackName.slug(agent.name() + " " + step.name());
		String brief = brief(agent, step);
		Skill skill = this.generator.generate(skillName, brief);
		String source = generateScript(step, brief);
		String scriptFileName = PackName.slug(step.name()) + ".js";
		Path skillDir = skillsDir.resolve(skillName);
		write(skillDir, skill, scriptFileName, source);
		return new Generated(skillName, skill, skillDir, scriptFileName);
	}

	/**
	 * The description the skill and the script are both generated from: the step's own
	 * declaration, so the skill is about this step and not about the process around it.
	 * @param agent the agent that owns the step
	 * @param step the action step
	 * @return the brief handed to both model calls.
	 */
	static String brief(AgentSpec agent, ActionStepSpec step) {
		return "Agent: " + agent.name() + "\n" + "Step: " + step.name() + "\n" + "What the step is for: "
				+ step.description() + "\n" + "Consumes: " + String.join(", ", step.inputTypeNames()) + "\n"
				+ "Produces: " + step.outputTypeName() + "\n" + "The step's own instruction:\n" + step.prompt();
	}

	/**
	 * The JavaScript source the model answered with.
	 * @param step the step the script implements
	 * @param brief the step's declaration, also carried so the script and the SKILL.md
	 * body describe the same work
	 * @return the source to write under {@code scripts/}.
	 */
	private String generateScript(ActionStepSpec step, String brief) {
		String user = "Below is one action step of an agent spec. Write the JavaScript script the skill named '"
				+ PackName.slug(step.name()) + ".js' needs, for the step named '" + step.name() + "'.\n\n"
				+ PromptData.block("step", brief);
		return LlmJson.callAndParse(this.caller, SCRIPT_PROMPT, user, 3, "the generated skill script",
				(raw) -> scriptOf(raw, step));
	}

	/**
	 * Reads the answered script out of the JSON object.
	 * @param json the outermost JSON object of the answer
	 * @param step the step named in the failure message
	 * @return the script source.
	 * @throws IllegalStateException when the answer carries no script, which the caller
	 * retries rather than accepts
	 */
	private static String scriptOf(String json, ActionStepSpec step) throws IOException {
		JsonNode node = JSON.readTree(json);
		String source = node.path("script").asText("");
		if (source.isBlank()) {
			throw new IllegalStateException("Script generation returned no script for step '" + step.name() + "'");
		}
		return source;
	}

	/**
	 * Writes the skill folder: {@code SKILL.md} rendered by the product's own
	 * {@link Skill#toSkillMd()}, and the script under {@code scripts/}.
	 * @param skillDir the folder to create
	 * @param skill the generated skill
	 * @param scriptFileName the script's file name
	 * @param source the script's source
	 */
	private static void write(Path skillDir, Skill skill, String scriptFileName, String source) {
		try {
			Files.createDirectories(skillDir.resolve("scripts"));
			Files.writeString(skillDir.resolve("SKILL.md"), skill.toSkillMd(), StandardCharsets.UTF_8);
			Files.writeString(skillDir.resolve("scripts").resolve(scriptFileName), source, StandardCharsets.UTF_8);
		}
		catch (IOException ex) {
			throw new UncheckedIOException("Failed to write the generated skill at " + skillDir, ex);
		}
	}

	/**
	 * A generated skill on disk: the folder, the skill it declares, and the script it
	 * carries. The folder is the artifact a candidate would carry, and
	 * {@link #script(String)} is the handle POC 26's engine takes for a script inside it.
	 *
	 * @param skillName the skill name, which is also the folder name
	 * @param skill the generated skill, whose {@link Skill#toSkillMd()} is what was
	 * written
	 * @param skillDir the folder that was written
	 * @param scriptFileName the generated script's file name under {@code scripts/}
	 * @author Ivan Rodriguez
	 */
	public record Generated(String skillName, Skill skill, Path skillDir, String scriptFileName) {

		/**
		 * The frontmatter verdict, from the product's own gate.
		 * @return the constraint violations, empty when the skill is well-formed.
		 */
		public List<String> frontmatterIssues() {
			return SkillMdValidator.validate(this.skill.name(), this.skill.description());
		}

		/**
		 * The JavaScript files the folder actually carries on disk, which is the only
		 * thing that makes a {@code scripts/} folder a {@code scripts/} folder.
		 * @return the script file names, sorted.
		 */
		public List<String> scriptFiles() {
			Path scripts = this.skillDir.resolve("scripts");
			if (!Files.isDirectory(scripts)) {
				return List.of();
			}
			try (Stream<Path> paths = Files.list(scripts)) {
				return paths.filter(Files::isRegularFile)
					.map((path) -> path.getFileName().toString())
					.filter((name) -> name.endsWith(".js"))
					.sorted()
					.toList();
			}
			catch (IOException ex) {
				throw new UncheckedIOException("Failed to list the scripts of " + this.skillDir, ex);
			}
		}

		/**
		 * The handle POC 26's engine runs, addressed the way Embabel addresses a skill's
		 * script: by skill name, file name and the folder that holds it.
		 * @param fileName the script file name, usually {@link #scriptFileName()}.
		 * @return the script to hand {@code SkillScriptExecutionEngine.execute}.
		 */
		public SkillScript script(String fileName) {
			return new SkillScript(this.skillName, fileName, ScriptLanguage.JAVASCRIPT, this.skillDir);
		}
	}

}
